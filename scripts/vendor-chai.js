'use strict';

// Writes src/core/vendor/chai.min.js: a minified copy of chai's browser bundle for the script
// sandbox. QuickJS spends most of a test script's start-up time parsing chai, and the minified
// copy parses in about half the time. Run `npm run vendor` after upgrading chai.
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const chaiDir = path.dirname(require.resolve('chai/package.json'));
const { version, license } = require('chai/package.json');
const source = fs.readFileSync(path.join(chaiDir, 'chai.js'), 'utf8');
const { code } = esbuild.transformSync(source, { minify: true, keepNames: true, legalComments: 'none', target: 'es2020' });
const header = `/*! chai ${version} (https://www.chaijs.com), ${license} License, Copyright (c) 2017 Chai.js Assertion Library. Generated by scripts/vendor-chai.js; do not edit. */\n`;
const out = path.join(__dirname, '..', 'src', 'core', 'vendor', 'chai.min.js');
fs.writeFileSync(out, header + code);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${(Buffer.byteLength(header + code) / 1024).toFixed(0)} KB) from chai ${version}`);
